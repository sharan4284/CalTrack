export async function compressImage(file, maxWidth = 800, quality = 0.8) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      const img = new Image();
      img.onload = () => {
        const canvas = document.createElement('canvas');
        let width = img.width;
        let height = img.height;

        if (width > maxWidth) {
          height = Math.round((height * maxWidth) / width);
          width = maxWidth;
        }

        canvas.width = width;
        canvas.height = height;
        const ctx = canvas.getContext('2d');
        ctx.drawImage(img, 0, 0, width, height);

        const dataUrl = canvas.toDataURL('image/jpeg', quality);
        resolve({
          dataUrl,
          width,
          height,
          sizeBytes: Math.round(dataUrl.length * 0.75)
        });
      };
      img.onerror = reject;
      img.src = e.target.result;
    };
    reader.onerror = reject;
    reader.readAsDataURL(file);
  });
}

// ─── Gemini Vision AI Call ───
export async function analyzeMealWithGemini(base64Image, apiKey) {
  if (!apiKey) throw new Error('No Gemini API key provided');

  // Strip prefix like "data:image/jpeg;base64,"
  const cleanBase64 = base64Image.replace(/^data:image\/[a-z]+;base64,/, '');

  const prompt = `Analyze this meal photo carefully. Provide nutritional estimate in strict JSON format:
{
  "dishName": "Short descriptive dish name",
  "calories": number,
  "protein": number (grams),
  "carbs": number (grams),
  "fat": number (grams),
  "fiber": number (grams),
  "servingSize": "e.g. 1 bowl (300g)",
  "confidence": "high" | "medium" | "low",
  "breakdown": ["Item 1: calories", "Item 2: calories"]
}
Only output the raw JSON, no markdown formatting or commentary.`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [
        {
          parts: [
            { text: prompt },
            {
              inlineData: {
                mimeType: 'image/jpeg',
                data: cleanBase64
              }
            }
          ]
        }
      ]
    })
  });

  if (!response.ok) {
    const errData = await response.json().catch(() => ({}));
    throw new Error(errData.error?.message || `API error ${response.status}`);
  }

  const json = await response.json();
  const textResponse = json.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!textResponse) throw new Error('No analysis generated by Vision model');

  // Extract JSON
  const match = textResponse.match(/\{[\s\S]*\}/);
  if (!match) throw new Error('Could not parse nutrition JSON from response');
  return JSON.parse(match[0]);
}

